use axum::response::IntoResponse;
use next_web_core::traits::desensitize::Desensitize;

/// A response wrapper that automatically redacts its payload before it is
/// sent to the client.
///
/// `Desensitized<T>` is a zero-cost newtype over `T`. It is constructed
/// through [`Desensitized::with`], which invokes [`Desensitize::desensitized`]
/// on the inner value **at construction time**. The wrapper therefore always
/// holds an already-redacted value; no further redaction happens when the
/// response is built.
///
/// This lets business handlers return raw data structures without ever
/// calling `desensitized()` manually, while still guaranteeing that the
/// outbound payload has been redacted.
///
/// # Redaction timing
///
/// Redaction is **eager**: it happens inside [`Desensitized::with`], not when
/// the response is serialized. This means:
///
/// - the redacted value is available for inspection before the response is
///   built (see [`Desensitized::inner`]);
/// - redaction errors surface at the call site of `with`, not deep inside
///   the response pipeline;
/// - repeated conversions via [`Desensitized::to_response`] do not re-run
///   redaction.
///
/// # Type parameters
///
/// - `T`: The wrapped response type. It must implement [`Desensitize`] so
///   that `with` can produce a redacted value. When the wrapper is converted
///   into a response via [`Desensitized::to_response`], `T` must also be usable
///   as the input of the mapping closure.
///
/// # Examples
///
/// ```ignore
/// async fn get_user() -> Response {
///     Desensitized::with(Json(fetch_user().await))
///         .to_response(|json| json)
/// }
/// ```
///
/// The handler above returns the raw `UserVo`, but the client receives the
/// redacted form because redaction happened inside `with`.
///
/// # Notes
///
/// - Redaction is applied to the *entire* inner value, not to individual
///   fields. Field-level control belongs to the `Desensitize` implementation
///   (typically generated by a derive macro).
/// - Because redaction happens eagerly, any failure inside
///   `Desensitize::desensitized` must be handled by the `Desensitize`
///   implementation itself (e.g. by falling back to a fully masked value).
///   The wrapper does not introduce an error channel of its own.
pub struct Desensitized<T>(T);

impl<T> Desensitized<T> {
    /// Wraps a response value and redacts it **immediately**.
    ///
    /// This constructor invokes [`Desensitize::desensitized`] on `inner` and
    /// stores the redacted result. The wrapper therefore never holds the raw,
    /// sensitive value after construction.
    ///
    /// # Why eager redaction
    ///
    /// Redacting at construction time rather than at serialization time gives
    /// three benefits:
    ///
    /// 1. **Inspectability** — the redacted value can be read via
    ///    [`Desensitized::inner`] before a response is built, which is useful
    ///    for logging, tests, or conditional response shaping.
    /// 2. **Fail fast** — any redaction error surfaces at the call site, close
    ///    to the business code that produced the data.
    /// 3. **No repeated work** — converting the wrapper into a response via
    ///    [`Desensitized::to_response`] does not re-run redaction.
    ///
    /// # Type bounds
    ///
    /// The `T: Desensitize` bound is enforced here. This makes `with` the only
    /// way to construct a `Desensitized<T>`, so the "this value is redacted"
    /// invariant holds for every instance.
    ///
    /// # Examples
    ///
    /// ```ignore
    /// let safe = Desensitized::with(Json(user_vo));
    /// // `safe` now holds the redacted payload.
    /// ```
    pub fn with(inner: T) -> Self
    where
        T: Desensitize,
    {
        Self(inner.desensitized())
    }

    /// Returns a reference to the wrapped value.
    ///
    /// Because redaction happens eagerly in [`Desensitized::with`], the
    /// returned reference always points to the **redacted** value. It never
    /// exposes the original sensitive data.
    ///
    /// Useful in tests, in logging, or in handlers that need to inspect the
    /// redacted payload before deciding how to shape the response.
    pub fn inner(&self) -> &T {
        &self.0
    }

    /// Consumes the wrapper and returns the wrapped value.
    ///
    /// The returned value is the **redacted** one produced by
    /// [`Desensitized::with`]. It is therefore safe to serialize, log, or
    /// forward without further redaction.
    ///
    /// Prefer [`Desensitized::to_response`] when the goal is to build a response,
    /// since it keeps the intent explicit.
    pub fn into_inner(self) -> T {
        self.0
    }

    /// Applies `f` to the redacted value and converts the result into a
    /// [`Response`].
    ///
    /// This is the intended exit point for handlers that need to customize
    /// the response shape (custom status code, extra headers, wrapping in a
    /// tuple, etc.) while preserving the wrapper's redaction guarantee.
    ///
    /// # Semantics
    ///
    /// `f` receives the **redacted** value stored in the wrapper, never the
    /// original sensitive data. The result `R` is then converted into an HTTP
    /// response via [`IntoResponse`].
    ///
    /// # Type bounds
    ///
    /// - `F`: a one-shot closure that maps the redacted `T` to some response
    ///   type `R`.
    /// - `R`: any type implementing [`IntoResponse`], so the mapped value can
    ///   be turned into an HTTP response by Axum.
    ///
    /// # Examples
    ///
    /// ```ignore
    /// let response = Desensitized::with(Json(user_vo))
    ///     .to_response(|json| (StatusCode::CREATED, json));
    /// ```
    pub fn to_response<F, R>(self, f: F) -> impl IntoResponse
    where
        F: FnOnce(T) -> R,
        R: IntoResponse,
    {
        f(self.into_inner())
    }
}
