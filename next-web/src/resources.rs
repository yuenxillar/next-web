//! Application resource loading.
//!
//! The framework reads its configuration, banner, messages, and other
//! resources through a [`ResourceLoader`](next_web_core::io::ResourceLoader).
//! By default the loader reads the `resources/` directory from the file
//! system. When the `embed-resources` feature is enabled and an application
//! annotates its entry point with
//! `#[next_application(resources = "...")]`, the files of that folder are
//! embedded into the binary and registered here, so the rest of the framework
//! uses them instead.

use std::sync::Arc;

use next_web_core::io::{DefaultResourceLoader, ResourceLoader};

#[cfg(feature = "embed-resources")]
use std::{
    borrow::Cow,
    collections::HashMap,
    io,
    path::{Path, PathBuf},
    sync::OnceLock,
};

#[cfg(feature = "embed-resources")]
use next_web_core::{io::Resource, util::matcher::AntPathMatcher};

/// The resource loader installed by the `#[next_application]` macro.
#[cfg(feature = "embed-resources")]
static EMBEDDED_RESOURCE_LOADER: OnceLock<Arc<dyn ResourceLoader>> = OnceLock::new();

/// Installs the resources of `T` as the resource loader of the application.
///
/// This function is called by the code generated by `#[next_application]`. It
/// reads every file of the folder named by the `resources` attribute, embeds
/// the files into the binary, and makes the framework read its configuration,
/// banner, and message bundles through the embedded loader instead of the file
/// system.
///
/// The first call wins: a second call does not replace the loader that was
/// installed already.
#[cfg(feature = "embed-resources")]
pub fn install_embedded_resources<T: rust_embed::Embed>() {
    let _ = EMBEDDED_RESOURCE_LOADER.set(embedded_resource_loader_from::<T>());
}

/// Returns the embedded resource loader, when one has been installed.
#[cfg(feature = "embed-resources")]
#[doc(hidden)]
pub fn embedded_resource_loader_from<T: rust_embed::Embed>() -> Arc<dyn ResourceLoader> {
    Arc::new(EmbeddedResourceLoader::from_embed::<T>())
}

/// Returns the installed embedded resource loader, when there is one.
#[cfg(feature = "embed-resources")]
pub(crate) fn embedded_resource_loader() -> Option<Arc<dyn ResourceLoader>> {
    EMBEDDED_RESOURCE_LOADER.get().cloned()
}

/// Returns a borrowed installed embedded resource loader, when there is one.
#[cfg(feature = "embed-resources")]
pub(crate) fn embedded_resource_loader_ref() -> Option<&'static dyn ResourceLoader> {
    EMBEDDED_RESOURCE_LOADER.get().map(|loader| loader.as_ref())
}

/// Returns the resource loader the framework uses by default.
///
/// The embedded loader wins when one has been installed; otherwise the shared
/// file system loader of [`DefaultResourceLoader`] is returned.
pub(crate) fn default_resource_loader() -> Arc<dyn ResourceLoader> {
    #[cfg(feature = "embed-resources")]
    if let Some(loader) = embedded_resource_loader() {
        return loader;
    }

    DefaultResourceLoader::shared_arc()
}

/// A resource loader backed by files embedded with `rust-embed`.
#[cfg(feature = "embed-resources")]
struct EmbeddedResourceLoader {
    resources: HashMap<Cow<'static, str>, EmbeddedResource>,
}

#[cfg(feature = "embed-resources")]
impl EmbeddedResourceLoader {
    /// Reads every file of the embedded type into the loader.
    fn from_embed<T: rust_embed::Embed>() -> Self {
        let mut resources = HashMap::new();

        for path in T::iter() {
            if let Some(file) = T::get(path.as_ref()) {
                resources.insert(
                    path.clone(),
                    EmbeddedResource {
                        path: PathBuf::from(path.as_ref()),
                        data: file.data,
                        last_modified: file.metadata.last_modified(),
                        created: file.metadata.created(),
                    },
                );
            }
        }

        Self { resources }
    }

    /// Normalizes the separators of a location.
    fn normalized(location: &str) -> Cow<'_, str> {
        if location.contains('\\') {
            Cow::Owned(location.replace('\\', "/"))
        } else {
            Cow::Borrowed(location)
        }
    }
}

#[cfg(feature = "embed-resources")]
impl ResourceLoader for EmbeddedResourceLoader {
    fn load(&mut self) -> io::Result<()> {
        Ok(())
    }

    fn refresh(&mut self) -> io::Result<()> {
        Ok(())
    }

    fn clear(&mut self) {
        // Embedded resources are immutable, so there is nothing to clear.
    }

    fn get_resource(&self, location: &str) -> io::Result<&dyn Resource> {
        let location = Self::normalized(location);

        self.resources
            .get(location.as_ref())
            .map(|resource| resource as &dyn Resource)
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, "resource not found"))
    }

    fn get_resources(&self, pattern: &str) -> io::Result<Vec<&dyn Resource>> {
        let normalized = pattern.replace('\\', "/");
        if normalized.trim().is_empty() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "pattern is empty",
            ));
        }

        let matcher = AntPathMatcher::default();
        let mut keys: Vec<&Cow<'static, str>> = self
            .resources
            .keys()
            .filter(|key| matcher.matches(&normalized, key))
            .collect();
        keys.sort();

        Ok(keys
            .into_iter()
            .filter_map(|key| self.resources.get(key))
            .map(|resource| resource as &dyn Resource)
            .collect())
    }

    fn get_directory(&self, location: &str) -> Vec<Cow<'static, str>> {
        let normalized = location.replace('\\', "/");
        let normalized = normalized.trim_matches('/');

        self.resources
            .keys()
            .filter(|key| {
                if let Some(rest) = key.strip_prefix(normalized) {
                    let rest = rest.strip_prefix('/').unwrap_or(rest);
                    !rest.is_empty() && !rest.contains('/')
                } else {
                    false
                }
            })
            .cloned()
            .collect()
    }

    fn paths(&self) -> Vec<Cow<'static, str>> {
        self.resources.keys().cloned().collect()
    }

    fn exists(&self, location: &str) -> bool {
        let location = Self::normalized(location);
        self.resources.contains_key(location.as_ref())
    }
}

/// A resource embedded into the binary.
#[cfg(feature = "embed-resources")]
struct EmbeddedResource {
    path: PathBuf,
    data: Cow<'static, [u8]>,
    last_modified: Option<u64>,
    created: Option<u64>,
}

#[cfg(feature = "embed-resources")]
impl Resource for EmbeddedResource {
    fn path(&self) -> io::Result<&Path> {
        Ok(&self.path)
    }

    fn get_content(&self) -> io::Result<Cow<'static, [u8]>> {
        Ok(self.data.clone())
    }

    fn content_length(&self) -> u64 {
        self.data.len() as u64
    }

    fn last_modified(&self) -> Option<u64> {
        self.last_modified
    }

    fn created(&self) -> Option<u64> {
        self.created
    }

    fn create_relative(&self, _relative_path: &str) -> io::Result<Box<dyn Resource>> {
        Err(io::Error::new(
            io::ErrorKind::Unsupported,
            "embedded resources do not support relative path resolution",
        ))
    }

    fn filename(&self) -> Option<&str> {
        self.path.file_name().and_then(|name| name.to_str())
    }
}

#[cfg(all(test, feature = "embed-resources"))]
mod tests {
    use super::*;

    #[derive(rust_embed::Embed, Debug)]
    #[folder = "tests/fixtures/embedded/"]
    struct TestResources;

    #[test]
    fn reads_an_embedded_resource() {
        let loader = EmbeddedResourceLoader::from_embed::<TestResources>();

        let resource = loader
            .get_resource("hello.txt")
            .expect("the embedded resource is available");

        assert_eq!(
            resource.get_content_as_string().unwrap().trim(),
            "embedded hello"
        );
    }

    #[test]
    fn installs_the_embedded_resource_loader() {
        install_embedded_resources::<TestResources>();

        let loader = default_resource_loader();
        let resource = loader
            .get_resource("hello.txt")
            .expect("the installed embedded resource is available");

        assert_eq!(
            resource.get_content_as_string().unwrap().trim(),
            "embedded hello"
        );
    }
}
