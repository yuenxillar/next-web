//! Application resource loading.
//!
//! The framework reads its configuration, banner, messages, and other
//! resources through a [`ResourceLoader`](next_web_core::io::ResourceLoader).
//! By default the loader reads the `resources/` directory from the file
//! system. When the `embed-resources` feature is enabled and an application
//! annotates its entry point with
//! `#[next_application(resources = "...")]`, the files of that folder are
//! embedded into the binary and registered here, so the rest of the framework
//! uses them instead.

use std::{fmt, sync::Arc};

use next_web_core::{
    env::{BindError, Binder, ConfigurableEnvironment},
    io::{DefaultResourceLoader, ResourceCacheConfig, ResourceLoader, web_resource_loader},
};
use next_web_macros::configuration_properties;
use serde::{Deserialize, Deserializer, Serialize, Serializer};

#[cfg(feature = "embed-resources")]
use std::{
    borrow::Cow,
    collections::HashMap,
    io,
    path::{Path, PathBuf},
    sync::OnceLock,
};

#[cfg(feature = "embed-resources")]
use next_web_core::{io::Resource, util::matcher::AntPathMatcher};

/// The resource loader installed by the `#[next_application]` macro.
#[cfg(feature = "embed-resources")]
static EMBEDDED_RESOURCE_LOADER: OnceLock<Arc<dyn ResourceLoader>> = OnceLock::new();

/// Installs the resources of `T` as the resource loader of the application.
///
/// This function is called by the code generated by `#[next_application]`. It
/// reads every file of the folder named by the `resources` attribute, embeds
/// the files into the binary, and makes the framework read its configuration,
/// banner, and message bundles through the embedded loader instead of the file
/// system.
///
/// The first call wins: a second call does not replace the loader that was
/// installed already.
#[cfg(feature = "embed-resources")]
pub fn install_embedded_resources<T: rust_embed::Embed>() {
    let _ = EMBEDDED_RESOURCE_LOADER.set(embedded_resource_loader_from::<T>());
}

/// Returns the embedded resource loader, when one has been installed.
#[cfg(feature = "embed-resources")]
#[doc(hidden)]
pub fn embedded_resource_loader_from<T: rust_embed::Embed>() -> Arc<dyn ResourceLoader> {
    Arc::new(EmbeddedResourceLoader::from_embed::<T>())
}

/// Returns the installed embedded resource loader, when there is one.
#[cfg(feature = "embed-resources")]
pub(crate) fn embedded_resource_loader() -> Option<Arc<dyn ResourceLoader>> {
    EMBEDDED_RESOURCE_LOADER.get().cloned()
}

/// Returns a borrowed installed embedded resource loader, when there is one.
#[cfg(feature = "embed-resources")]
pub(crate) fn embedded_resource_loader_ref() -> Option<&'static dyn ResourceLoader> {
    EMBEDDED_RESOURCE_LOADER.get().map(|loader| loader.as_ref())
}

/// Returns the resource loader the framework uses by default.
///
/// The embedded loader wins when one has been installed; otherwise the shared
/// file system loader of [`DefaultResourceLoader`] is returned, unless the
/// application installed the loader the web layer reads from, see
/// [`resource_loader_from_environment`].
pub(crate) fn default_resource_loader() -> Arc<dyn ResourceLoader> {
    #[cfg(feature = "embed-resources")]
    if let Some(loader) = embedded_resource_loader() {
        return loader;
    }

    web_resource_loader()
}

/// Builds the resource loader of the application from its environment.
///
/// The loader reads the resources a web application serves with the cache the
/// [`ResourceProperties`] of the environment configure, so an application that
/// sets `next.resources.cache.max_file_size` and
/// `next.resources.cache.max_total_size` reads its resources with the limits it
/// configured. An environment that configures none binds the defaults of
/// [`ResourceCacheConfig`].
///
/// The embedded loader wins when one has been installed, because the resources
/// of the application are part of the binary and no directory is scanned.
///
/// # Arguments
///
/// * `environment` - The environment the properties are bound from.
pub(crate) fn resource_loader_from_environment(
    environment: &dyn ConfigurableEnvironment,
) -> Arc<dyn ResourceLoader> {
    #[cfg(feature = "embed-resources")]
    if let Some(loader) = embedded_resource_loader() {
        return loader;
    }

    let cache_config = match ResourceProperties::from_environment(environment) {
        Ok(properties) => properties.to_cache_config(),
        Err(error) => {
            tracing::warn!("the properties of the resources could not be bound: {error}");
            ResourceCacheConfig::default()
        }
    };

    let mut loader = DefaultResourceLoader::with_cache_config(cache_config);
    if let Err(error) = loader.load() {
        tracing::debug!("the resources of the application could not be read: {error}");
    }

    Arc::new(loader)
}

/// The prefix the properties of the resources are bound from.
pub const RESOURCE_PROPERTIES_PREFIX: &str = "next.resources";

/// The properties of the resources of an application.
///
/// The properties are bound from the `next.resources` prefix of the environment
/// of the application:
///
/// ```yaml
/// next:
///   resources:
///     cache:
///       max_file_size: 5mb
///       max_total_size: 64mb
///       panic_on_overflow: false
/// ```
///
/// A size is read from a number of bytes or from text with a unit, so
/// `max_file_size: 5242880` and `max_file_size: 5mb` configure the same limit.
/// A `max_total_size` of `0` disables the limit of the total size of the cache.
#[configuration_properties(prefix = "next.resources")]
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct ResourceProperties {
    /// The cache of the resources that are read into memory.
    cache: ResourceCacheProperties,
}

impl ResourceProperties {
    /// Reads the properties from the environment, using the default of a field
    /// the environment does not configure.
    ///
    /// # Errors
    ///
    /// Returns a [`BindError`] when a property of the environment cannot be read
    /// as the type of its field, for example when a size holds text that is not
    /// a size.
    pub fn from_environment(environment: &dyn ConfigurableEnvironment) -> Result<Self, BindError> {
        Binder::new(environment, RESOURCE_PROPERTIES_PREFIX).bind::<Self>()
    }

    /// Returns the cache of the properties.
    pub fn cache(&self) -> &ResourceCacheProperties {
        &self.cache
    }

    /// Builds the cache configuration the loader reads the resources with.
    pub fn to_cache_config(&self) -> ResourceCacheConfig {
        ResourceCacheConfig {
            max_file_size: self.cache.max_file_size.bytes(),
            max_total_size: self.cache.max_total_size.bytes(),
            panic_on_overflow: self.cache.panic_on_overflow,
        }
    }
}

impl Default for ResourceProperties {
    fn default() -> Self {
        Self {
            cache: ResourceCacheProperties::default(),
        }
    }
}

/// The cache of the resources an application reads into memory.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct ResourceCacheProperties {
    /// The largest resource that is cached.
    ///
    /// A resource whose content is larger is skipped, and so is a resource that
    /// would push the total size of the cache over
    /// [`max_total_size`](Self::max_total_size).
    max_file_size: ByteSize,

    /// The largest total size of the cache.
    ///
    /// A value of `0` disables the limit of the total size.
    max_total_size: ByteSize,

    /// Whether a resource that does not fit the limits panics.
    ///
    /// A resource that does not fit is skipped when this is `false`, which is
    /// the default, and panics when it is `true`.
    panic_on_overflow: bool,
}

impl ResourceCacheProperties {
    /// Returns the largest resource that is cached.
    pub fn max_file_size(&self) -> ByteSize {
        self.max_file_size
    }

    /// Returns the largest total size of the cache, which `0` disables.
    pub fn max_total_size(&self) -> ByteSize {
        self.max_total_size
    }

    /// Returns whether a resource that does not fit the limits panics.
    pub fn panic_on_overflow(&self) -> bool {
        self.panic_on_overflow
    }
}

impl Default for ResourceCacheProperties {
    fn default() -> Self {
        let defaults = ResourceCacheConfig::default();

        Self {
            max_file_size: ByteSize(defaults.max_file_size),
            max_total_size: ByteSize(defaults.max_total_size),
            panic_on_overflow: defaults.panic_on_overflow,
        }
    }
}

/// A size, read from a number of bytes or from text with a unit.
///
/// The units are the binary ones, so `5mb` and `5MiB` are the same size:
/// `b`, `kb`/`kib`, `mb`/`mib`, `gb`/`gib`, and `tb`/`tib`. The unit is
/// compared without case, and the text may hold spaces, so `5 MB` is read as
/// well as `5mb`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ByteSize(u64);

impl ByteSize {
    /// Returns the size of `bytes` bytes.
    pub const fn of_bytes(bytes: u64) -> Self {
        Self(bytes)
    }

    /// Returns the size in bytes.
    pub const fn bytes(self) -> u64 {
        self.0
    }
}

impl From<u64> for ByteSize {
    fn from(bytes: u64) -> Self {
        Self(bytes)
    }
}

impl From<ByteSize> for u64 {
    fn from(size: ByteSize) -> Self {
        size.0
    }
}

impl fmt::Display for ByteSize {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl Serialize for ByteSize {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_u64(self.0)
    }
}

impl<'de> Deserialize<'de> for ByteSize {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        #[derive(Deserialize)]
        #[serde(untagged)]
        enum Value {
            /// A size written as a number of bytes.
            Bytes(u64),
            /// A size written with a unit, such as `5mb`.
            Text(String),
        }

        match Value::deserialize(deserializer)? {
            Value::Bytes(bytes) => Ok(Self(bytes)),
            Value::Text(text) => parse_byte_size(&text)
                .map(Self)
                .map_err(serde::de::Error::custom),
        }
    }
}

/// Reads a size written with a unit, such as `5mb`, as a number of bytes.
///
/// # Errors
///
/// Returns a message when the text is not a number, when its unit is unknown,
/// or when the size does not fit a `u64`.
fn parse_byte_size(text: &str) -> Result<u64, String> {
    let text = text.trim();
    let split = text
        .find(|character: char| !character.is_ascii_digit() && character != '_')
        .unwrap_or(text.len());
    let (digits, unit) = text.split_at(split);

    let value: u64 = digits
        .replace('_', "")
        .parse()
        .map_err(|_| format!("`{text}` is not a size"))?;

    let multiplier: u64 = match unit.trim().to_ascii_lowercase().as_str() {
        "" | "b" => 1,
        "k" | "kb" | "kib" => 1024,
        "m" | "mb" | "mib" => 1024 * 1024,
        "g" | "gb" | "gib" => 1024 * 1024 * 1024,
        "t" | "tb" | "tib" => 1024 * 1024 * 1024 * 1024,
        unit => return Err(format!("`{unit}` is not a unit of a size")),
    };

    value
        .checked_mul(multiplier)
        .ok_or_else(|| format!("`{text}` is too large"))
}

/// A resource loader backed by files embedded with `rust-embed`.
#[cfg(feature = "embed-resources")]
struct EmbeddedResourceLoader {
    resources: HashMap<Cow<'static, str>, EmbeddedResource>,
}

#[cfg(feature = "embed-resources")]
impl EmbeddedResourceLoader {
    /// Reads every file of the embedded type into the loader.
    fn from_embed<T: rust_embed::Embed>() -> Self {
        let mut resources = HashMap::new();

        for path in T::iter() {
            if let Some(file) = T::get(path.as_ref()) {
                resources.insert(
                    path.clone(),
                    EmbeddedResource {
                        path: PathBuf::from(path.as_ref()),
                        data: file.data,
                        last_modified: file.metadata.last_modified(),
                        created: file.metadata.created(),
                    },
                );
            }
        }

        Self { resources }
    }

    /// Normalizes the separators of a location.
    fn normalized(location: &str) -> Cow<'_, str> {
        if location.contains('\\') {
            Cow::Owned(location.replace('\\', "/"))
        } else {
            Cow::Borrowed(location)
        }
    }
}

#[cfg(feature = "embed-resources")]
impl ResourceLoader for EmbeddedResourceLoader {
    fn load(&mut self) -> io::Result<()> {
        Ok(())
    }

    fn refresh(&mut self) -> io::Result<()> {
        Ok(())
    }

    fn clear(&mut self) {
        // Embedded resources are immutable, so there is nothing to clear.
    }

    fn get_resource(&self, location: &str) -> io::Result<&dyn Resource> {
        let location = Self::normalized(location);

        self.resources
            .get(location.as_ref())
            .map(|resource| resource as &dyn Resource)
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, "resource not found"))
    }

    fn get_resources(&self, pattern: &str) -> io::Result<Vec<&dyn Resource>> {
        let normalized = pattern.replace('\\', "/");
        if normalized.trim().is_empty() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "pattern is empty",
            ));
        }

        let matcher = AntPathMatcher::default();
        let mut keys: Vec<&Cow<'static, str>> = self
            .resources
            .keys()
            .filter(|key| matcher.matches(&normalized, key))
            .collect();
        keys.sort();

        Ok(keys
            .into_iter()
            .filter_map(|key| self.resources.get(key))
            .map(|resource| resource as &dyn Resource)
            .collect())
    }

    fn get_directory(&self, location: &str) -> Vec<Cow<'static, str>> {
        let normalized = location.replace('\\', "/");
        let normalized = normalized.trim_matches('/');

        self.resources
            .keys()
            .filter(|key| {
                if let Some(rest) = key.strip_prefix(normalized) {
                    let rest = rest.strip_prefix('/').unwrap_or(rest);
                    !rest.is_empty() && !rest.contains('/')
                } else {
                    false
                }
            })
            .cloned()
            .collect()
    }

    fn paths(&self) -> Vec<Cow<'static, str>> {
        self.resources.keys().cloned().collect()
    }

    fn exists(&self, location: &str) -> bool {
        let location = Self::normalized(location);
        self.resources.contains_key(location.as_ref())
    }
}

/// A resource embedded into the binary.
#[cfg(feature = "embed-resources")]
struct EmbeddedResource {
    path: PathBuf,
    data: Cow<'static, [u8]>,
    last_modified: Option<u64>,
    created: Option<u64>,
}

#[cfg(feature = "embed-resources")]
impl Resource for EmbeddedResource {
    fn path(&self) -> io::Result<&Path> {
        Ok(&self.path)
    }

    fn get_content(&self) -> io::Result<Cow<'static, [u8]>> {
        Ok(self.data.clone())
    }

    fn content_length(&self) -> u64 {
        self.data.len() as u64
    }

    fn last_modified(&self) -> Option<u64> {
        self.last_modified
    }

    fn created(&self) -> Option<u64> {
        self.created
    }

    fn create_relative(&self, _relative_path: &str) -> io::Result<Box<dyn Resource>> {
        Err(io::Error::new(
            io::ErrorKind::Unsupported,
            "embedded resources do not support relative path resolution",
        ))
    }

    fn filename(&self) -> Option<&str> {
        self.path.file_name().and_then(|name| name.to_str())
    }
}

#[cfg(all(test, feature = "embed-resources"))]
mod tests {
    use super::*;

    #[derive(rust_embed::Embed, Debug)]
    #[folder = "tests/fixtures/embedded/"]
    struct TestResources;

    #[test]
    fn reads_an_embedded_resource() {
        let loader = EmbeddedResourceLoader::from_embed::<TestResources>();

        let resource = loader
            .get_resource("hello.txt")
            .expect("the embedded resource is available");

        assert_eq!(
            resource.get_content_as_string().unwrap().trim(),
            "embedded hello"
        );
    }

    #[test]
    fn installs_the_embedded_resource_loader() {
        install_embedded_resources::<TestResources>();

        let loader = default_resource_loader();
        let resource = loader
            .get_resource("hello.txt")
            .expect("the installed embedded resource is available");

        assert_eq!(
            resource.get_content_as_string().unwrap().trim(),
            "embedded hello"
        );
    }
}

#[cfg(test)]
mod properties_tests {
    use next_web_core::{
        env::{BaseEnvironment, ConfigurableEnvironment, MapPropertySource},
        io::ResourceCacheConfig,
        util::indexmap::IndexMap,
    };

    use super::{ByteSize, ResourceProperties};

    /// Creates an environment holding the given properties.
    fn environment(properties: &[(&str, &str)]) -> BaseEnvironment {
        let mut environment = BaseEnvironment::new();
        environment
            .property_sources()
            .add_last(Box::new(MapPropertySource::new(
                "test".to_owned(),
                properties
                    .iter()
                    .map(|(key, value)| ((*key).to_owned(), (*value).to_owned()))
                    .collect::<IndexMap<_, _>>(),
            )));

        environment
    }

    #[test]
    fn a_size_is_read_from_a_number_of_bytes() {
        assert_eq!(ByteSize::of_bytes(5_242_880).bytes(), 5_242_880);
        assert_eq!(ByteSize::from(1024u64).bytes(), 1024);
    }

    #[test]
    fn a_size_is_read_from_text_with_a_unit() {
        let properties: ResourceProperties = serde_yaml::from_str(
            r#"
            cache:
              max_file_size: 5mb
              max_total_size: 512 KiB
            "#,
        )
        .expect("the document is read");

        assert_eq!(properties.cache().max_file_size().bytes(), 5 * 1024 * 1024);
        assert_eq!(properties.cache().max_total_size().bytes(), 512 * 1024);
    }

    #[test]
    fn a_size_is_read_from_a_number_of_bytes_of_a_document() {
        let properties: ResourceProperties =
            serde_yaml::from_str("cache:\n  max_file_size: 5242880\n")
                .expect("the document is read");

        assert_eq!(properties.cache().max_file_size().bytes(), 5_242_880);
        // The field the document does not configure keeps its default.
        assert_eq!(
            properties.cache().max_total_size().bytes(),
            ResourceCacheConfig::default().max_total_size
        );
    }

    #[test]
    fn a_size_that_is_not_a_size_is_refused() {
        let error = serde_yaml::from_str::<ResourceProperties>("cache:\n  max_file_size: 5mo\n")
            .expect_err("`mo` is not a unit of a size");

        assert!(error.to_string().contains("mo"), "{error}");
    }

    #[test]
    fn the_defaults_are_the_defaults_of_the_cache_config() {
        let defaults = ResourceCacheConfig::default();
        let properties = ResourceProperties::default();

        assert_eq!(
            properties.to_cache_config(),
            ResourceCacheConfig {
                max_file_size: defaults.max_file_size,
                max_total_size: defaults.max_total_size,
                panic_on_overflow: defaults.panic_on_overflow,
            }
        );
        assert_eq!(properties.cache().max_file_size().bytes(), 5 * 1024 * 1024);
        assert_eq!(
            properties.cache().max_total_size().bytes(),
            64 * 1024 * 1024
        );
        assert!(!properties.cache().panic_on_overflow());
    }

    #[test]
    fn the_properties_are_bound_from_the_environment() {
        let environment = environment(&[
            ("next.resources.cache.max_file_size", "10mb"),
            ("next.resources.cache.max_total_size", "0"),
            ("next.resources.cache.panic_on_overflow", "true"),
        ]);

        let properties =
            ResourceProperties::from_environment(&environment).expect("the properties bind");

        assert_eq!(properties.cache().max_file_size().bytes(), 10 * 1024 * 1024);
        assert_eq!(properties.cache().max_total_size().bytes(), 0);
        assert!(properties.cache().panic_on_overflow());
        assert_eq!(
            properties.to_cache_config(),
            ResourceCacheConfig {
                max_file_size: 10 * 1024 * 1024,
                max_total_size: 0,
                panic_on_overflow: true,
            }
        );
    }

    #[test]
    fn an_environment_that_configures_no_resource_binds_the_defaults() {
        let environment = environment(&[("next.application.name", "demo")]);

        let properties =
            ResourceProperties::from_environment(&environment).expect("the properties bind");

        assert_eq!(properties, ResourceProperties::default());
    }
}
