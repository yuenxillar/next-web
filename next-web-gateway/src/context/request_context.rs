//! Per-request state shared by the proxy and every filter.

use std::collections::HashMap;
use std::sync::Arc;
use std::time::Instant;

use bytes::Bytes;
use pingora::{
    Result,
    http::{RequestHeader, ResponseHeader},
};

use crate::filter::factory::local_response_cache::{
    LocalResponseCacheManager, LocalResponseCacheRequestState, PendingLocalResponseCacheEntry,
};
use crate::upstream::UpstreamSelection;

/// State of one request/response exchange.
#[derive(Clone, Default)]
pub struct RequestContext {
    /// Correlation id echoed to the client and sent upstream.
    pub request_id: String,
    /// Values captured by `Path` predicate templates.
    pub path_variables: HashMap<String, String>,
    /// Route that matched, if any.
    pub route_id: Option<String>,
    /// Circuit breaker id referenced by `CircuitBreaker=<id>`.
    pub fallback_id: Option<String>,
    /// Downstream peer address, resolved once by the proxy.
    pub client_ip: Option<std::net::IpAddr>,
    /// Downstream `Host` as the client sent it.
    pub original_host: Option<String>,
    /// Whether `PreserveHostHeader` asked for the downstream `Host` to win.
    pub preserve_host: bool,
    /// Host to send upstream, set by `SetRequestHostHeader`.
    pub upstream_host_override: Option<String>,
    /// Upstream selected for this request.
    pub selected: Option<UpstreamSelection>,
    /// Path as received, before any rewrite.
    pub original_request_path: Option<String>,
    /// Bytes of request body seen so far.
    pub request_body_bytes: u64,
    /// Whether this request was counted in the inflight gauge.
    pub inflight_counted: bool,
    /// When the request started, used for latency logs.
    pub started: Option<Instant>,
    /// Whether the response body is being buffered for a body filter.
    pub buffer_response_body: bool,
    /// Buffered response body.
    pub response_body_buffer: Vec<u8>,
    /// Set when the buffer exceeded its limit and filtering was abandoned.
    pub buffer_overflowed: bool,
    /// Response cache manager, when the route caches.
    pub local_response_cache_manager: Option<Arc<LocalResponseCacheManager>>,
    /// Request side cache state.
    pub local_response_cache_request: Option<LocalResponseCacheRequestState>,
    /// Entry waiting to be stored once the body is complete.
    pub pending_local_response_cache: Option<PendingLocalResponseCacheEntry>,
    /// Session identifier, currently never populated.
    pub session: Option<String>,
    /// Response generated by the gateway itself.
    pub direct_response: Option<DirectResponse>,
}

/// A response the gateway generates without contacting an upstream.
#[derive(Clone)]
pub struct DirectResponse {
    /// Status line to send.
    pub status: u16,
    /// Headers to send.
    pub headers: Vec<(String, String)>,
    /// Body to send.
    pub body: Bytes,
}

impl RequestContext {
    /// Answer with a text body and stop the filter chain.
    pub fn respond_with_text(
        &mut self,
        status: u16,
        headers: Vec<(String, String)>,
        body: impl Into<String>,
    ) -> Result<()> {
        self.direct_response = Some(DirectResponse {
            status,
            headers,
            body: Bytes::from(body.into()),
        });

        Err(pingora::Error::new(pingora::ErrorType::HTTPStatus(status)))
    }

    /// Answer with an empty body and stop the filter chain.
    pub fn respond_with_empty(
        &mut self,
        status: u16,
        headers: Vec<(String, String)>,
    ) -> Result<()> {
        self.direct_response = Some(DirectResponse {
            status,
            headers,
            body: Bytes::new(),
        });

        Err(pingora::Error::new(pingora::ErrorType::HTTPStatus(status)))
    }

    /// Answer with a binary body and stop the filter chain.
    pub fn respond_with_body(
        &mut self,
        status: u16,
        headers: Vec<(String, String)>,
        body: Bytes,
    ) -> Result<()> {
        self.direct_response = Some(DirectResponse {
            status,
            headers,
            body,
        });

        Err(pingora::Error::new(pingora::ErrorType::HTTPStatus(status)))
    }

    /// Milliseconds elapsed since the request started.
    pub fn elapsed_millis(&self) -> u128 {
        self.started
            .map(|started| started.elapsed().as_millis())
            .unwrap_or(0)
    }
}

/// The part of the exchange a filter is allowed to touch.
#[derive(Debug)]
pub enum HeaderAndBody<'a, 'b> {
    /// A request header, and optionally a request body chunk.
    Req {
        /// Request header under edit.
        req_header: Option<&'a mut RequestHeader>,
        /// Request body under edit.
        req_body: Option<&'b mut Bytes>,
    },
    /// A response header, and optionally a response body chunk.
    Resp {
        /// Response body under edit.
        resp_body: Option<&'b mut Bytes>,
        /// Response header under edit.
        resp_header: Option<&'a mut ResponseHeader>,
    },
    /// Nothing to edit in this pass.
    None,
}

impl<'a, 'b> HeaderAndBody<'a, 'b> {
    /// Wrap a request header.
    pub fn with_req_header(req_header: &'a mut RequestHeader) -> Self {
        Self::Req {
            req_header: Some(req_header),
            req_body: None,
        }
    }

    /// Wrap a response header.
    pub fn with_resp_header(resp_header: &'a mut ResponseHeader) -> Self {
        Self::Resp {
            resp_body: None,
            resp_header: Some(resp_header),
        }
    }

    /// Wrap a request body chunk.
    pub fn with_req_body(req_body: &'b mut Option<Bytes>) -> Self {
        Self::Req {
            req_header: None,
            req_body: req_body.as_mut(),
        }
    }

    /// Wrap a response body chunk.
    pub fn with_resp_body(resp_body: &'b mut Option<Bytes>) -> Self {
        Self::Resp {
            resp_body: resp_body.as_mut(),
            resp_header: None,
        }
    }
}
