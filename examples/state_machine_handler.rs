//! A function marked with `#[on_transition]` runs when the machine takes the
//! transition it filters for.
//!
//! The attribute targets `::next_web::state_machine` by default, so an
//! application which depends on the umbrella crate needs nothing else. A project
//! which depends on the state machine crate directly passes
//! `crate = next_web_state_machine`.
//!
//! Building the machine directly is fine for an example; an application usually
//! lets a `StateMachineService` own it instead.

use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};

use next_web::state_machine::config::base_state_machine_factory::BaseStateMachineFactory;
use next_web::state_machine::config::model::configuration_data::ConfigurationData;
use next_web::state_machine::config::model::default_state_machine_model::DefaultStateMachineModel;
use next_web::state_machine::config::model::state_data::StateData;
use next_web::state_machine::config::model::transition_data::TransitionData;
use next_web::state_machine::config::model::transitions_data::TransitionsData;
use next_web::state_machine::config::state_machine_factory::StateMachineFactory;
use next_web::state_machine::state_context::StateContext;
use next_web_core::error::BoxError;
use next_web_core::messaging::generic_message::GenericMessage;

/// Counts how often the handler ran.
static AUDITS: AtomicUsize = AtomicUsize::new(0);

/// Runs when the machine leaves the state 1 for the state 2 on the event 100.
#[next_web::on_transition(source = 1, target = 2, event = 100)]
fn audit(_context: &dyn StateContext<i32, i32>) -> Result<(), BoxError> {
    AUDITS.fetch_add(1, Ordering::SeqCst);

    Ok(())
}

#[tokio::main]
async fn main() {
    let configuration = ConfigurationData::<i32, i32>::with_parameters(
        false,
        None,
        Vec::new(),
        false,
        None,
        None,
        None,
        None,
        false,
        None,
        Some("handler".to_owned()),
        None,
        Vec::new(),
    );

    let model = DefaultStateMachineModel::new(
        configuration,
        Some(
            vec![
                StateData::<i32, i32>::with_initial(1, true),
                StateData::<i32, i32>::new(2),
            ]
            .into(),
        ),
        Some(TransitionsData::new(vec![TransitionData::new(1, 2, 100)])),
    );

    let machine = BaseStateMachineFactory::<i32, i32>::new(Arc::new(model), None)
        .get_state_machine()
        .expect("the machine builds from its configuration");

    // `audit_handler()` is generated by the attribute.
    machine
        .add_transition_handler(Arc::new(audit_handler()))
        .expect("the handler is registered");

    machine.start().await.expect("the machine starts");

    machine
        .send_event(Arc::new(GenericMessage::with_payload(100)))
        .await
        .expect("the event is sent");

    let audits = AUDITS.load(Ordering::SeqCst);

    assert_eq!(audits, 1, "the handler ran once for the transition");

    // The machine is in state 2 and the handler filters on the source state 1, so
    // an event it does not filter for must not run it again.
    machine
        .send_event(Arc::new(GenericMessage::with_payload(999)))
        .await
        .expect("the event is sent");

    assert_eq!(
        AUDITS.load(Ordering::SeqCst),
        1,
        "the handler ignores an event it does not filter for"
    );
    assert_eq!(
        machine.state().map(|state| *state.id()),
        Some(2),
        "the transition moved the machine"
    );

    println!("audited: {audits}");

    machine.stop().await.expect("the machine stops");
}
