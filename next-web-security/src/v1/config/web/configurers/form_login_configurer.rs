/// Adds form based authentication. All attributes have reasonable defaults making all parameters are optional.
/// If no loginPage(String) is specified, a default login page will be generated by the framework.
#[derive(Clone)]
pub struct FormLoginConfigurer<H>
where
    H: HttpSecurityBuilder<H>,
{
    /// The login page given through the DSL, installed when the configurer is
    /// initialized because the entry point needs the builder.
    custom_login_page: Option<Box<str>>,

    base: BaseAuthenticationFilterConfigurer<H, Self, UsernamePasswordAuthenticationFilter>,
}

impl<H> FormLoginConfigurer<H>
where
    H: HttpSecurityBuilder<H>,
    H: 'static,
{
    /// Specifies the URL to send users to if login is required.
    ///
    /// The page replaces the generated login page, and the entry point of the
    /// chain redirects to it. It is installed when the configurer is initialized,
    /// because updating the entry point needs the builder, which a DSL closure
    /// does not have.
    pub fn login_page(&mut self, login_page: &str) -> &mut Self {
        self.custom_login_page = Some(login_page.into());
        self
    }

    /// Specifies the URL the login form is submitted to. Default is
    /// `"/login"`.
    pub fn login_processing_url(&mut self, login_processing_url: &str) -> &mut Self {
        <Self as BaseAuthenticationFilterConfigurerExt<H>>::login_processing_url(
            self,
            login_processing_url,
        );
        self
    }

    /// The HTTP parameter to look for the username when performing authentication. Default
    /// is `"username"`.
    ///
    /// # Arguments
    ///
    /// * `username_parameter` - the HTTP parameter to look for the username when
    ///   performing authentication
    ///
    /// # Returns
    ///
    /// The `FormLoginConfigurer` for additional customization
    pub fn username_parameter(&mut self, username_parameter: &str) -> &mut Self {
        self.get_authentication_filter_mut()
            .map(|filter| filter.set_username_parameter(username_parameter));

        self
    }

    /// The HTTP parameter to look for the password when performing authentication. Default
    /// is `"password"`.
    ///
    /// # Arguments
    ///
    /// * `password_parameter` - the HTTP parameter to look for the password when
    ///   performing authentication
    ///
    /// # Returns
    ///
    /// The `FormLoginConfigurer` for additional customization
    pub fn password_parameter(&mut self, password_parameter: &str) -> &mut Self {
        self.get_authentication_filter_mut()
            .map(|filter| filter.set_password_parameter(password_parameter));

        self
    }

    /// Forward Authentication Failure Handler
    ///
    /// # Arguments
    ///
    /// * `forward_url` - the target URL in case of failure
    ///
    /// # Returns
    ///
    /// The `FormLoginConfigurer` for additional customization
    pub fn failure_forward_url(&mut self, forward_url: &str) -> &mut Self {
        self.failure_handler(Arc::new(ForwardAuthenticationFailureHandler::new(
            forward_url,
        )));

        self
    }

    /// Forward Authentication Success Handler
    ///
    /// # Arguments
    ///
    /// * `forward_url` - the target URL in case of success
    ///
    /// # Returns
    ///
    /// The `FormLoginConfigurer` for additional customization
    pub fn success_forward_url(&mut self, forward_url: &str) -> &mut Self {
        self.success_handler(Arc::new(ForwardAuthenticationSuccessHandler::new(
            forward_url,
        )));

        self
    }

    /// Gets the HTTP parameter that is used to submit the username.
    ///
    /// # Returns
    ///
    /// The HTTP parameter that is used to submit the username
    fn get_username_parameter(&self) -> &str {
        self.get_authentication_filter()
            .map(|filter| filter.get_username_parameter())
            .unwrap_or_default()
    }

    /// Gets the HTTP parameter that is used to submit the password.
    ///
    /// # Returns
    ///
    /// The HTTP parameter that is used to submit the password
    fn get_password_parameter(&self) -> &str {
        self.get_authentication_filter()
            .map(|filter| filter.get_password_parameter())
            .unwrap_or_default()
    }

    /// If available, initializes the `DefaultLoginPageGeneratingFilter` shared
    /// object.
    ///
    /// # Arguments
    ///
    /// * `http` - the `HttpSecurityBuilder` to use
    pub(crate) fn init_default_login_filter(&mut self, http: &mut H) {
        if let Some(login_page_generating_filter) =
            http.shared_object_mut::<DefaultLoginPageGeneratingFilter>()
        {
            if !self.is_custom_login_page() {
                login_page_generating_filter.set_form_login_enabled(true);
                login_page_generating_filter.set_username_parameter(self.get_username_parameter());
                login_page_generating_filter.set_password_parameter(self.get_password_parameter());
                login_page_generating_filter.set_login_page_url(self.get_login_page());

                self.get_failure_url()
                    .map(|s| login_page_generating_filter.set_failure_url(s));

                self.get_login_processing_url()
                    .map(|s| login_page_generating_filter.set_authentication_url(s));
            }
        }
    }
}

impl<H> SecurityConfigurer<DefaultSecurityFilterChain, H> for FormLoginConfigurer<H>
where
    H: HttpSecurityBuilder<H>,
    H: 'static,
{
    fn init(&mut self, http: &mut H) {
        // A login page given through the DSL replaces the generated one, so it is
        // installed before the defaults are updated around it.
        if let Some(login_page) = self.custom_login_page.clone() {
            <Self as BaseAuthenticationFilterConfigurerExt<H>>::login_page(
                self,
                login_page.as_ref(),
                http,
            );
        }

        self.base.init(http);
        self.init_default_login_filter(http);

        // Configure exception handling
        let request_matcher = self.get_authentication_entry_point_matcher(http);
        if let Some(error_handling_configurer) = http.configurer_mut::<ErrorHandlingConfigurer<H>>()
        {
            let entry_point = self.get_authentication_entry_point();
            error_handling_configurer.default_denied_handler_for_missing_authority_with_builder(
                |builer| {
                    entry_point.map(|ep| {
                        builer.add_entry_point_for(Arc::new(ep.to_owned()), request_matcher)
                    });
                },
                FactorGrantedAuthority::PASSWORD_AUTHORITY,
            );
        }
    }

    fn configure(&mut self, http: &mut H) {
        self.base.configure(http);
    }
}

impl<H> BaseAuthenticationFilterConfigurerExt<H> for FormLoginConfigurer<H>
where
    H: HttpSecurityBuilder<H>,
    H: 'static,
{
    /// Specifies the URL to send users to if login is required. If used with
    /// `EnableWebSecurity` a default login page will be generated when this
    /// attribute is not specified.
    ///
    /// If a URL is specified or this is not being used in conjunction with
    /// `EnableWebSecurity`, users are required to process the specified URL to
    /// generate a login page. In general, the login page should create a form that submits
    /// a request with the following requirements to work with
    /// `UsernamePasswordAuthenticationFilter`:
    ///
    /// * It must be an HTTP POST
    /// * It must be submitted to `login_processing_url`
    /// * It should include the username as an HTTP parameter by the name of
    ///   `username_parameter`
    /// * It should include the password as an HTTP parameter by the name of
    ///   `password_parameter`
    ///
    /// # Impact on other defaults
    ///
    /// Updating this value, also impacts a number of other default values. For example,
    /// the following are the default values when only `form_login()` was specified.
    ///
    /// * `/login` GET - the login form
    /// * `/login` POST - process the credentials and if valid authenticate the user
    /// * `/login?error` GET - redirect here for failed authentication attempts
    /// * `/login?logout` GET - redirect here after successfully logging out
    ///
    /// If `"/authenticate"` was passed to this method it updates the defaults as shown below:
    ///
    /// * `/authenticate` GET - the login form
    /// * `/authenticate` POST - process the credentials and if valid authenticate the user
    /// * `/authenticate?error` GET - redirect here for failed authentication attempts
    /// * `/authenticate?logout` GET - redirect here after successfully logging out
    ///
    /// # Arguments
    ///
    /// * `login_page` - the login page to redirect to if authentication is required (i.e.
    ///   `"/login"`)
    ///
    /// # Returns
    ///
    /// The `FormLoginConfigurer` for additional customization
    fn login_page(&mut self, login_page: &str, http: &mut H) {
        self.base.login_page(login_page, http);
    }

    fn login_processing_url(&mut self, login_processing_url: &str) {
        self.base.login_processing_url = Some(login_processing_url.into());

        let requires_authentication_request_matcher =
            self.create_login_processing_url_matcher(login_processing_url);
        self.base.auth_filter.as_mut().map(|filter| {
            filter.set_requires_authentication_request_matcher(
                requires_authentication_request_matcher,
            )
        });
    }

    fn create_login_processing_url_matcher(
        &self,
        login_processing_url: &str,
    ) -> Arc<dyn RequestMatcher> {
        Arc::new(
            DEFAULT_BUILDER
                .get_or_init(|| Default::default())
                .matcher(Some(HttpMethod::POST), login_processing_url),
        )
    }
}

impl<H> Default for FormLoginConfigurer<H>
where
    H: HttpSecurityBuilder<H>,
    H: 'static,
{
    fn default() -> Self {
        let mut configurer = Self {
            custom_login_page: None,
            base: BaseAuthenticationFilterConfigurer::new(
                UsernamePasswordAuthenticationFilter::default(),
                None,
            ),
        };
        configurer
            .username_parameter("username")
            .password_parameter("password");

        configurer
    }
}

impl<H> Deref for FormLoginConfigurer<H>
where
    H: HttpSecurityBuilder<H>,
{
    type Target = BaseAuthenticationFilterConfigurer<H, Self, UsernamePasswordAuthenticationFilter>;

    fn deref(&self) -> &Self::Target {
        &self.base
    }
}

impl<H> DerefMut for FormLoginConfigurer<H>
where
    H: HttpSecurityBuilder<H>,
{
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.base
    }
}

#[cfg(test)]
mod tests {
    use std::collections::HashMap;

    use super::*;
    use crate::config::{
        authentication::builders::authentication_manager_builder::AuthenticationManagerBuilder,
        web::builders::HttpSecurity,
    };

    /// Returns an HTTP security a configurer can be applied to.
    fn http_security() -> HttpSecurity {
        HttpSecurity::new(AuthenticationManagerBuilder::default(), HashMap::new())
    }

    #[test]
    fn a_custom_login_page_is_installed_as_the_entry_point() {
        let mut http = http_security();
        let mut configurer = FormLoginConfigurer::<HttpSecurity>::default();
        configurer.login_page("/custom-login");

        configurer.init(&mut http);

        assert!(configurer.is_custom_login_page());
        assert_eq!(
            configurer
                .get_authentication_entry_point()
                .map(|point| point.get_login_form_url().to_owned()),
            Some("/custom-login".to_owned())
        );
    }

    #[test]
    fn a_custom_login_processing_url_is_kept() {
        let mut configurer = FormLoginConfigurer::<HttpSecurity>::default();

        configurer.login_processing_url("/do-login");

        assert_eq!(
            configurer.get_login_processing_url(),
            Some("/do-login")
        );
    }

    mod flow {
        use std::sync::Arc;

        use axum::{body::Body, extract::Request, response::Response};
        use next_web_core::http::{HttpRequest, RequestBody};

        use super::*;
        use crate::{
            authentication::dao::DaoAuthenticationProvider,
            config::security_builder::SecurityBuilder,
            config::web::http_security_builder::HttpSecurityBuilder,
            core::userdetails::{User, UserDetailsService},
            crypto::{bcrypt::BCryptPasswordEncoder, password::PasswordEncoder},
            provisioning::InMemoryUserDetailsManager,
            web::security_filter_chain::SecurityFilterChain,
            web::test_support::Chain,
        };

        /// Returns a `POST` of the login form.
        fn login_request(username: &str, password: &str) -> Request {
            let body = format!("username={username}&password={password}");
            let mut request = Request::builder()
                .method("POST")
                .uri("https://sp.example.org/login")
                .body(Body::empty())
                .expect("a valid request");
            request
                .extensions_mut()
                .insert(RequestBody::new(body.into_bytes()));

            request
        }

        /// Returns a `POST` of the given path, with no body.
        fn post_request(path: &str) -> Request {
            Request::builder()
                .method("POST")
                .uri(format!("https://sp.example.org{path}"))
                .body(Body::empty())
                .expect("a valid request")
        }

        /// Returns the `Location` header of a response.
        fn redirect_of(response: &Response) -> Option<String> {
            response
                .headers()
                .get("location")
                .and_then(|value| value.to_str().ok())
                .map(str::to_owned)
        }

        /// Returns the name of the authenticated principal, if one was stored.
        fn authenticated_username(request: &dyn HttpRequest) -> Option<String> {
            use next_web_core::any::AnyValue;

            let AnyValue::BoxedValue(value) = request.get_attribute(
                crate::web::context::RequestAttributeSecurityContextRepository::
                    DEFAULT_REQUEST_ATTR_NAME,
            )?
            else {
                return None;
            };
            let context = (**value)
                .as_any()
                .downcast_ref::<Arc<dyn crate::core::context::SecurityContext>>()?;

            context
                .get_authentication()
                .and_then(|authentication| authentication.principal().map(|p| p.to_string()))
        }

        /// Returns an HTTP security whose form login authenticates `user`.
        fn http_security(password_hash: &str) -> HttpSecurity {
            // The logout configurer takes its matcher from a shared builder, the
            // way the configuration of an application provides one.
            let mut shared_objects: HashMap<
                std::any::TypeId,
                Box<dyn next_web_core::any::AnyClone>,
            > = HashMap::new();
            shared_objects.insert(
                std::any::TypeId::of::<crate::web::util::matcher::PathPatternRequestMatcherBuilder>(
                ),
                Box::new(crate::web::util::matcher::PathPatternRequestMatcherBuilder::default()),
            );

            let mut http =
                HttpSecurity::new(AuthenticationManagerBuilder::default(), shared_objects);
            http.form_login(|_| {});

            let user_details_service: Arc<dyn UserDetailsService> =
                Arc::new(InMemoryUserDetailsManager::with_users(vec![Arc::new(
                    User::with_username("user")
                        .password(Some(password_hash.to_string()))
                        .build(),
                )]));
            let mut provider = DaoAuthenticationProvider::new(user_details_service);
            provider.set_password_encoder(Arc::new(BCryptPasswordEncoder::new(4)));
            http.authentication_provider(Arc::new(provider));

            http
        }

        #[tokio::test]
        async fn a_form_login_authenticates_through_the_chain() {
            let encoder = BCryptPasswordEncoder::new(4);
            let hash = encoder
                .encode(Some("password"))
                .expect("the password is encoded")
                .expect("the encoder returns a hash");
            let mut http = http_security(&hash);
            let chain = http.build();
            let filters = Arc::new(chain.get_filters().to_vec());

            let mut request = login_request("user", "password");
            let mut response = Response::default();
            Chain::new(filters)
                .run(&mut request, &mut response)
                .await
                .expect("the chain runs");

            assert!(
                response.status().is_redirection(),
                "the login redirects, status was {}",
                response.status()
            );
            assert_eq!(redirect_of(&response), Some("/".to_owned()));
            assert_eq!(authenticated_username(&request).as_deref(), Some("user"));
        }

        #[tokio::test]
        async fn a_wrong_password_does_not_authenticate() {
            let encoder = BCryptPasswordEncoder::new(4);
            let hash = encoder
                .encode(Some("password"))
                .expect("the password is encoded")
                .expect("the encoder returns a hash");
            let mut http = http_security(&hash);
            let chain = http.build();
            let filters = Arc::new(chain.get_filters().to_vec());

            let mut request = login_request("user", "wrong");
            let mut response = Response::default();
            Chain::new(filters)
                .run(&mut request, &mut response)
                .await
                .expect("the chain runs");

            assert_eq!(
                redirect_of(&response),
                Some("/login?error".to_owned()),
                "a failed login sends the user back to the login page"
            );
            assert_eq!(authenticated_username(&request), None);
        }

        /// Returns an HTTP security whose form login authenticates `user` and
        /// whose chain can log the user out again.
        fn http_security_with_logout(password_hash: &str) -> HttpSecurity {
            let mut http = http_security(password_hash);
            http.logout(|_| {});

            http
        }

        /// Returns a request with an HTTP Basic authorization header.
        fn basic_request(username: &str, password: &str) -> Request {
            use base64::Engine;

            let credentials = base64::engine::general_purpose::STANDARD
                .encode(format!("{username}:{password}"));

            Request::builder()
                .method("GET")
                .uri("https://sp.example.org/api/users")
                .header("authorization", format!("Basic {credentials}"))
                .body(Body::empty())
                .expect("a valid request")
        }

        #[tokio::test]
        async fn http_basic_authenticates_through_the_chain() {
            let encoder = BCryptPasswordEncoder::new(4);
            let hash = encoder
                .encode(Some("password"))
                .expect("the password is encoded")
                .expect("the encoder returns a hash");
            let mut http = http_security(&hash);
            http.http_basic(|_| {});
            let chain = http.build();
            let filters = Arc::new(chain.get_filters().to_vec());

            let mut request = basic_request("user", "password");
            let mut response = Response::default();
            Chain::new(filters)
                .run(&mut request, &mut response)
                .await
                .expect("the chain runs");

            assert_eq!(
                authenticated_username(&request).as_deref(),
                Some("user"),
                "the credentials of the header authenticate the user"
            );
        }

        #[tokio::test]
        async fn http_basic_without_credentials_does_not_authenticate() {
            let encoder = BCryptPasswordEncoder::new(4);
            let hash = encoder
                .encode(Some("password"))
                .expect("the password is encoded")
                .expect("the encoder returns a hash");
            let mut http = http_security(&hash);
            http.http_basic(|_| {});
            let chain = http.build();
            let filters = Arc::new(chain.get_filters().to_vec());

            let mut request = post_request("/api/users");
            let mut response = Response::default();
            Chain::new(filters)
                .run(&mut request, &mut response)
                .await
                .expect("the chain runs");

            assert_eq!(
                authenticated_username(&request),
                None,
                "without a header nothing is authenticated"
            );
        }

        #[tokio::test]
        async fn a_logged_in_user_can_be_logged_out() {
            let encoder = BCryptPasswordEncoder::new(4);
            let hash = encoder
                .encode(Some("password"))
                .expect("the password is encoded")
                .expect("the encoder returns a hash");
            let mut http = http_security_with_logout(&hash);
            let chain = http.build();
            let filters = Arc::new(chain.get_filters().to_vec());

            let mut login = login_request("user", "password");
            let mut login_response = Response::default();
            Chain::new(filters.clone())
                .run(&mut login, &mut login_response)
                .await
                .expect("the chain runs");
            assert_eq!(authenticated_username(&login).as_deref(), Some("user"));

            let mut logout = post_request("/logout");
            let mut logout_response = Response::default();
            Chain::new(filters)
                .run(&mut logout, &mut logout_response)
                .await
                .expect("the chain runs");

            assert!(
                logout_response.status().is_redirection(),
                "the logout redirects, status was {}",
                logout_response.status()
            );
            assert_eq!(
                redirect_of(&logout_response),
                Some("/login?logout".to_owned()),
                "the user is sent back to the login page"
            );
            assert_eq!(
                authenticated_username(&logout),
                None,
                "the logout leaves no authentication behind"
            );
        }
    }
}
