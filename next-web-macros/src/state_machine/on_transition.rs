//! The `#[on_transition]` attribute macro.
//!
//! It is the Rust counterpart of the `@OnTransition` methods of the Java
//! implementation: the annotated function keeps its name and its body, and the
//! macro adds a function which builds the handler the machine registers.
//!
//! The handler hook of the machine runs synchronously, so the annotated function
//! is synchronous as well. A function which needs to do asynchronous work reads
//! what it needs from the context and spawns the work itself.

use proc_macro::TokenStream;
use quote::{format_ident, quote};
use syn::{
    Expr, FnArg, GenericArgument, ItemFn, PathArguments, ReturnType, Token, Type, parse_macro_input,
    punctuated::Punctuated,
};

/// Wraps a transition handler function.
///
/// The function receives the state context and returns a result, and the macro
/// generates `<name>_handler()` which returns the handler for the state machine.
///
/// # Arguments
/// * `source = ..` - only run for transitions which leave this state
/// * `target = ..` - only run for transitions which enter this state
/// * `event = ..` - only run for transitions triggered by this event
pub fn impl_macro_on_transition(attr: TokenStream, item: TokenStream) -> TokenStream {
    let function = parse_macro_input!(item as ItemFn);

    match expand(&function, attr) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

/// Expands the handler function into the function and its handler builder.
fn expand(function: &ItemFn, attr: TokenStream) -> syn::Result<proc_macro2::TokenStream> {
    let (state_type, event_type) = context_types(function)?;
    let arguments = arguments(attr)?;

    let name = &function.sig.ident;
    let handler = format_ident!("{}_handler", name);

    // The generated code targets the re-export of the umbrella crate by
    // default, because that is the crate an application depends on. A project
    // which depends on the state machine crate directly passes
    // `crate = next_web_state_machine`.
    let root = arguments
        .krate
        .map(|path| quote! { #path })
        .unwrap_or_else(|| quote! { ::next_web::state_machine });

    let source = arguments.conditions.source.map(|expression| {
        quote! { .source(#expression) }
    });
    let target = arguments.conditions.target.map(|expression| {
        quote! { .target(#expression) }
    });
    let event = arguments.conditions.event.map(|expression| {
        quote! { .event(#expression) }
    });

    let document = format!(
        "Builds the `{name}` transition handler.\n\n\
         Generated by `#[on_transition]`; register it with \
         `machine.add_transition_handler(Arc::new({handler}()))`."
    );

    Ok(quote! {
        #function

        #[doc = #document]
        pub fn #handler() -> #root::handler::on_transition::OnTransition<
            #state_type,
            #event_type,
        > {
            #root::handler::on_transition::OnTransition::new(
                ::std::sync::Arc::new(
                    |context: &dyn #root::state_context::StateContext<
                        #state_type,
                        #event_type,
                    >| #name(context),
                ),
            )
            #source
            #target
            #event
        }
    })
}

/// The arguments of the attribute.
#[derive(Default)]
struct Arguments {
    /// The path of the state machine crate, when it is re-exported
    krate: Option<syn::Path>,
    conditions: Conditions,
}

/// The conditions of the attribute.
#[derive(Default)]
struct Conditions {
    source: Option<Expr>,
    target: Option<Expr>,
    event: Option<Expr>,
}

/// One `name = value` argument of the attribute.
enum Argument {
    /// The `crate = path` argument
    Crate(syn::Path),
    /// A condition such as `source = 1`
    Condition(syn::Ident, Expr),
}

impl syn::parse::Parse for Argument {
    fn parse(input: syn::parse::ParseStream) -> syn::Result<Self> {
        if input.peek(Token![crate]) {
            input.parse::<Token![crate]>()?;
            input.parse::<Token![=]>()?;

            return Ok(Self::Crate(input.parse()?));
        }

        let name: syn::Ident = input.parse()?;
        input.parse::<Token![=]>()?;

        Ok(Self::Condition(name, input.parse()?))
    }
}

/// Parses the `crate`, `source`, `target` and `event` arguments.
fn arguments(attr: TokenStream) -> syn::Result<Arguments> {
    let parser = Punctuated::<Argument, Token![,]>::parse_terminated;

    let arguments = syn::parse::Parser::parse(parser, attr)?;
    let mut parsed = Arguments::default();

    for argument in arguments {
        match argument {
            Argument::Crate(path) => parsed.krate = Some(path),
            Argument::Condition(identifier, value) => match identifier.to_string().as_str() {
                "source" => parsed.conditions.source = Some(value),
                "target" => parsed.conditions.target = Some(value),
                "event" => parsed.conditions.event = Some(value),
                other => {
                    return Err(syn::Error::new_spanned(
                        identifier,
                        format!(
                            "unknown argument `{other}`, expected `crate`, `source`, `target` or `event`"
                        ),
                    ));
                }
            },
        }
    }

    Ok(parsed)
}

/// Extracts the state and the event type from the context parameter.
fn context_types(function: &ItemFn) -> syn::Result<(Type, Type)> {
    let Some(argument) = function.sig.inputs.first() else {
        return Err(syn::Error::new_spanned(
            &function.sig,
            "the handler needs the state context as its first parameter",
        ));
    };

    let context = match argument {
        FnArg::Typed(argument) => &*argument.ty,
        FnArg::Receiver(receiver) => {
            return Err(syn::Error::new_spanned(
                receiver,
                "the handler has to be a free function, not a method",
            ));
        }
    };

    let Type::Reference(reference) = context else {
        return Err(syn::Error::new_spanned(
            context,
            "the first parameter has to be `&dyn StateContext<S, E>`",
        ));
    };

    let Type::TraitObject(object) = &*reference.elem else {
        return Err(syn::Error::new_spanned(
            &reference.elem,
            "the first parameter has to be `&dyn StateContext<S, E>`",
        ));
    };

    let Some(bound) = object.bounds.first() else {
        return Err(syn::Error::new_spanned(
            object,
            "the first parameter has to be `&dyn StateContext<S, E>`",
        ));
    };

    let syn::TypeParamBound::Trait(bound) = bound else {
        return Err(syn::Error::new_spanned(
            bound,
            "the first parameter has to be `&dyn StateContext<S, E>`",
        ));
    };

    let PathArguments::AngleBracketed(arguments) = &bound.path.segments.last().map_or(
        PathArguments::None,
        |segment| segment.arguments.clone(),
    ) else {
        return Err(syn::Error::new_spanned(
            &bound.path,
            "the first parameter has to be `&dyn StateContext<S, E>`",
        ));
    };

    let mut types = arguments.args.iter().filter_map(|argument| match argument {
        GenericArgument::Type(Type::Path(path)) => Some(Type::Path(path.clone())),
        GenericArgument::Type(other) => Some(other.clone()),
        _ => None,
    });

    let Some(state_type) = types.next() else {
        return Err(syn::Error::new_spanned(
            &bound.path,
            "the state context is missing its state type",
        ));
    };

    let Some(event_type) = types.next() else {
        return Err(syn::Error::new_spanned(
            &bound.path,
            "the state context is missing its event type",
        ));
    };

    Ok((state_type, event_type))
}

/// Keeps the return type of the handler in the signature of the generated
/// function, so a handler which does not return a result is rejected here.
#[allow(dead_code)]
fn ensures_result(function: &ItemFn) -> syn::Result<()> {
    match &function.sig.output {
        ReturnType::Default => Err(syn::Error::new_spanned(
            &function.sig,
            "the handler has to return `Result<(), BoxError>`",
        )),
        ReturnType::Type(_, _) => Ok(()),
    }
}
